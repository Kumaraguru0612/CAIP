        f"| Alert Reduction | — | **{ar.get('alert_reduction_pct','—')}%** |",
        f"| Precision | {_fmt(bl.get('precision'))} | {_fmt(cp.get('precision'))} |",
        f"| Recall | {_fmt(bl.get('recall'))} | {_fmt(cp.get('recall'))} |",
        f"| F1 | {_fmt(bl.get('f1'))} | **{_fmt(cp.get('f1'))}** |",
        f"| False Positive Rate | {_fmt(bl.get('fpr'))} | **{_fmt(cp.get('fpr'))}** |",
        "",
        f"> **Key finding**: CAIP reduces alert volume by {ar.get('alert_reduction_pct','?')}% "
        f"while grouping {ar.get('total_events','?')} events into {cp.get('campaigns','?')} campaigns.",
