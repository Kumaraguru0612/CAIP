sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from shared.experiment_runner import RESULTS_DIR, ensure_results_dir

EXPERIMENTS = [
    ("Experiment 1: Baseline vs CAIP",           "exp1_baseline_vs_caip",     "exp1_results"),
    ("Experiment 2: Ablation Study",             "exp2_ablation_study",       "exp2_results"),
    ("Experiment 3: Correlation Signals",        "exp3_correlation_signals",  "exp3_results"),
    ("Experiment 4: Prediction Validation",      "exp4_prediction_validation","exp4_results"),
    ("Experiment 5: Twin Decision Quality",      "exp5_twin_decision",        "exp5_results"),
    ("Experiment 6: Cost-Aware Routing",         "exp6_cost_routing",         "exp6_results"),
    ("Experiment 7: Zero-Day Generalization",    "exp7_unseen_generalization","exp7_results"),
]


def run_all():
    print("\n" + "=" * 70)
    print("  CAIP IEEE Experiment Suite — Running All 7 Experiments")
    print("=" * 70)
    ensure_results_dir()

    results = {}
    total_start = time.time()

    for title, module_name, result_key in EXPERIMENTS:
        print(f"\n{'-'*70}")
        print(f"  >>  {title}")
        print(f"{'-'*70}")
        try:
            mod = __import__(module_name)
            result = mod.run_experiment()
            results[result_key] = result
            print(f"  [OK] {title} -- DONE")
        except Exception as e:
            print(f"  [FAIL] {title} -- ERROR: {e}")
            import traceback
            traceback.print_exc()
            results[result_key] = {"error": str(e)}

    total_sec = time.time() - total_start
    print(f"\n\n{'='*70}")
    print(f"  All experiments completed in {total_sec:.1f}s")
    print(f"  Results saved to: {RESULTS_DIR}")
    print(f"{'='*70}\n")

    generate_ieee_summary(results)
    return results


def _fmt(v, pct=False, decimals=4):
    if v is None or v == "—": return "—"
    if isinstance(v, float):
        if pct: return f"{v*100:.1f}%"
        return f"{v:.{decimals}f}"
    return str(v)


